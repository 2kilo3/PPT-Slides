const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
const { chromium } = require('playwright');
const { execFileSync } = require('node:child_process');

(async () => {
  const root = path.resolve(__dirname, '..'), work = path.join(root,'work/test');
  await fs.mkdir(work,{recursive:true});
  const input = path.join(work,'demo.html');
  execFileSync(process.env.PYTHON || 'python',[path.join(root,'scripts/bundle.py'),path.join(root,'examples/starter.html'),input]);
  const browser = await chromium.launch({headless:true});
  const passed = [];
  try {
    const context = await browser.newContext({viewport:{width:1280,height:720},acceptDownloads:true});
    const page = await context.newPage(), errors = [], network = [];
    page.on('pageerror', e => errors.push(e.message));
    await context.route(/^https?:/, route => {network.push(route.request().url());return route.abort();});
    await page.goto(pathToFileURL(input).href);
    await page.waitForFunction(() => window.PPTStudio);
    assert.equal(await page.locator('.slide.active').count(),1);
    await page.keyboard.press('End'); assert.equal(await page.evaluate(()=>PPTStudio.index),2);
    await page.keyboard.press('ArrowRight'); assert.equal(await page.evaluate(()=>PPTStudio.index),2);
    await page.keyboard.press('Home');
    for(let i=0;i<15;i++) await page.keyboard.press(i%2?'ArrowLeft':'ArrowRight');
    assert.equal(await page.locator('.slide[aria-hidden="false"]').count(),1);
    passed.push('keyboard bounds and rapid navigation');
    await page.keyboard.press('Home'); await page.keyboard.press('e');
    const field=page.locator('[data-edit-id=opening-lead]');
    await field.fill('修改后的中文内容 <不作为 HTML 执行>');
    await page.keyboard.press('ArrowRight'); assert.equal(await page.evaluate(()=>PPTStudio.index),0);
    await page.keyboard.press('Escape');
    assert.equal(await field.getAttribute('contenteditable'),null);
    await page.reload(); await page.waitForFunction(()=>window.PPTStudio);
    assert.equal(await field.textContent(),'修改后的中文内容 <不作为 HTML 执行>');
    assert.equal(await page.locator('[data-edit-id=opening-title] br').count(),1);
    passed.push('plain text editing, focus-safe keyboard, draft persistence and unchanged markup');
    const popupEvent=page.waitForEvent('popup'); await page.keyboard.press('n');
    const popup=await popupEvent; await popup.waitForSelector('textarea');
    await popup.locator('textarea').fill('新的逐页讲稿 & 特殊字符 <script>');
    await page.evaluate(()=>PPTStudio.go(1));
    assert.match(await popup.locator('textarea').inputValue(),/现场演讲/);
    await popup.locator('textarea').fill('第二页讲稿');
    await popup.locator('[data-forward]').click(); assert.equal(await page.evaluate(()=>PPTStudio.index),2);
    await popup.locator('[data-prev]').click(); assert.equal(await page.evaluate(()=>PPTStudio.index),1);
    assert.equal(await popup.locator('textarea').inputValue(),'第二页讲稿');
    await page.evaluate(()=>PPTStudio.go(0));
    assert.equal(await popup.locator('textarea').inputValue(),'新的逐页讲稿 & 特殊字符 <script>');
    const oldSize=await popup.locator('textarea').evaluate(e=>getComputedStyle(e).fontSize);
    await popup.locator('[data-larger]').click();
    assert.notEqual(await popup.locator('textarea').evaluate(e=>getComputedStyle(e).fontSize),oldSize);
    await popup.locator('[data-clock]').click();
    await popup.waitForFunction(()=>document.querySelector('[data-timer]').textContent!=='00:00');
    await popup.locator('[data-clock]').click();
    const paused=await popup.locator('[data-timer]').textContent();
    await page.waitForTimeout(1100);assert.equal(await popup.locator('[data-timer]').textContent(),paused);
    await popup.locator('[data-reset]').click();assert.equal(await popup.locator('[data-timer]').textContent(),'00:00');
    passed.push('presenter two-way navigation, focused-note switch, notes, font size, timer pause/reset');
    const exportEvent=page.waitForEvent('download');await page.evaluate(()=>PPTStudio.exportHTML());
    const exported=await exportEvent;const exportedPath=path.join(work,'edited.html');await exported.saveAs(exportedPath);
    const fresh=await browser.newContext();const reopened=await fresh.newPage();
    await reopened.goto(pathToFileURL(exportedPath).href);await reopened.waitForFunction(()=>window.PPTStudio);
    assert.equal(await reopened.locator('[data-edit-id=opening-lead]').textContent(),'修改后的中文内容 <不作为 HTML 执行>');
    assert.equal(await reopened.locator('.studio-toolbar').count(),1);
    assert.equal(await reopened.locator('.slide.active').count(),1);
    assert.equal(await reopened.locator('[data-slide-id=opening] template').evaluate(e=>e.content.textContent),'新的逐页讲稿 & 特殊字符 <script>');
    await reopened.keyboard.press('e');await reopened.locator('[data-edit-id=opening-lead]').fill('再次编辑');
    passed.push('export/reopen in clean browser retains edits and supports another edit');
    const notesEvent=page.waitForEvent('download');await page.evaluate(()=>PPTStudio.exportNotes());
    const notesDownload=await notesEvent;const notesPath=path.join(work,'notes.md');await notesDownload.saveAs(notesPath);
    assert.match(await fs.readFile(notesPath,'utf8'),/第二页讲稿/);
    passed.push('Markdown notes export');
    const modified=(await fs.readFile(input,'utf8')).replace('选定视觉方向，组织页面层次，带着讲稿开始讲解。','来自新版源文件');
    await fs.writeFile(path.join(work,'updated.html'),modified);
    const updated=await context.newPage();await updated.goto(pathToFileURL(path.join(work,'updated.html')).href);
    await updated.waitForFunction(()=>window.PPTStudio);
    assert.equal(await updated.locator('[data-edit-id=opening-lead]').textContent(),'来自新版源文件');
    assert.match(await updated.locator('[role=status]').textContent(),/旧草稿未覆盖/);
    passed.push('stale browser drafts cannot overwrite changed source');
    const reversed=await page.evaluate(()=>{const root=new DOMParser().parseFromString(PPTStudio.snapshot(),'text/html');const stage=root.querySelector('.deck-stage');stage.prepend(stage.lastElementChild);return '<!doctype html>'+root.documentElement.outerHTML;});
    await fs.writeFile(path.join(work,'reordered.html'),reversed);
    await reopened.goto(pathToFileURL(path.join(work,'reordered.html')).href);await reopened.waitForFunction(()=>window.PPTStudio);
    assert.equal(await reopened.locator('.slide.active').getAttribute('data-slide-id'),'delivery');
    assert.match(await reopened.locator('.slide.active template').evaluate(e=>e.content.textContent),/演示文字修改/);
    passed.push('reordered slides keep their own notes');
    await reopened.emulateMedia({reducedMotion:'reduce'});
    assert.equal(await reopened.locator('.slide.active .reveal').first().evaluate(e=>getComputedStyle(e).animationName),'none');
    await reopened.setViewportSize({width:390,height:844});
    await reopened.evaluate(()=>new Promise(resolve=>requestAnimationFrame(resolve)));
    const rect=await reopened.locator('.deck-stage').boundingBox();assert.ok(Math.abs(rect.width/rect.height-16/9)<0.001);
    passed.push('reduced motion and phone 16:9 geometry');
    // Use a page without a presenter so popup-close propagation cannot race this check.
    await popup.close();await updated.evaluate(()=>{window.open=()=>null;PPTStudio.openPresenter();});
    assert.match(await updated.locator('[role=status]').textContent(),/允许弹窗/);
    passed.push('blocked presenter popup reports recovery without exposing notes');
    assert.deepEqual(errors,[]);assert.deepEqual(network,[]);
    await fs.writeFile(path.join(work,'runtime-report.json'),JSON.stringify({status:'PASS',passed,errors,network},null,2));
    console.log(JSON.stringify({status:'PASS',checks:passed.length,passed},null,2));
  } finally {await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
